"""Local degraded-mode cache for the Raspberry kiosk."""

from __future__ import annotations

import hashlib
import json
import os
import sqlite3
import uuid
from dataclasses import dataclass
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any


START_GRACE_MINUTES = int(os.environ.get("OFFLINE_START_GRACE_MINUTES", "5"))
END_GRACE_MINUTES = int(os.environ.get("OFFLINE_END_GRACE_MINUTES", "10"))
DEFAULT_DB_PATH = Path(__file__).resolve().parent / "offline_cache.sqlite3"


def utc_now() -> datetime:
    """Return a timezone-aware UTC timestamp."""
    return datetime.now(timezone.utc)


def parse_datetime(value: str | None) -> datetime | None:
    """Parse an ISO timestamp from the backend into an aware datetime."""
    if not value:
        return None
    parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
    if parsed.tzinfo is None:
        return parsed.replace(tzinfo=timezone.utc)
    return parsed.astimezone(timezone.utc)


def hash_secret(value: str) -> str:
    """Hash a user-provided local credential exactly like the backend."""
    return hashlib.sha256(value.encode("utf-8")).hexdigest()


def parse_qr_payload(value: str) -> dict[str, str] | None:
    """Parse the reservation QR format generated by the backend."""
    raw = (value or "").strip()
    if not raw:
        return None

    try:
        payload = json.loads(raw)
    except json.JSONDecodeError:
        payload = None

    if isinstance(payload, dict) and payload.get("type") == "reservation_access":
        reservation_code = str(payload.get("reservation") or "").strip().upper()
        token = str(payload.get("token") or "").strip()
        if reservation_code and token:
            return {"reservation_code": reservation_code, "token": token}

    if raw.startswith("station:reservation:"):
        parts = raw.split(":", 3)
        if len(parts) == 4 and parts[2] and parts[3]:
            return {"reservation_code": parts[2].strip().upper(), "token": parts[3].strip()}

    return None


@dataclass(frozen=True)
class OfflineAuthResult:
    """Result returned after a local degraded-mode validation."""

    reservation: dict[str, Any]
    session_id: str
    session_created: bool = True

    def to_payload(self) -> dict[str, Any]:
        """Return the same compact shape the kiosk expects from online auth."""
        reservation = self.reservation
        return {
            "message": "Authentification offline reussie.",
            "offline": True,
            "session_created": self.session_created,
            "session": {
                "id": self.session_id,
                "station": reservation["station_nom"],
                "borne": reservation.get("borne_nom") or "-",
                "borne_numero": reservation.get("borne_numero"),
                "mqtt_prefix": reservation.get("mqtt_prefix") or "",
                "emplacement": reservation["emplacement_numero"],
                "slot_id": reservation.get("slot_id") or f"slot{reservation['emplacement_numero']}",
                "start_time": utc_now().isoformat(),
                "end_time": None,
                "status": "active",
            },
            "reservation": reservation,
        }


class OfflineStore:
    """SQLite-backed cache of reservations and offline events."""

    def __init__(self, db_path: str | os.PathLike[str] | None = None):
        self.db_path = Path(db_path or os.environ.get("OFFLINE_DB_PATH") or DEFAULT_DB_PATH)
        self.db_path.parent.mkdir(parents=True, exist_ok=True)
        self._init_db()

    def _connect(self):
        connection = sqlite3.connect(self.db_path)
        connection.row_factory = sqlite3.Row
        return connection

    def _init_db(self):
        with self._connect() as connection:
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS cached_reservations (
                    id_reservation TEXT PRIMARY KEY,
                    reference_code TEXT NOT NULL,
                    station_id TEXT NOT NULL,
                    station_nom TEXT NOT NULL,
                    emplacement_id TEXT NOT NULL,
                    emplacement_numero INTEGER NOT NULL,
                    auth_mode TEXT NOT NULL,
                    auth_hash TEXT NOT NULL,
                    auth_expires_at TEXT,
                    date_debut TEXT NOT NULL,
                    date_fin TEXT NOT NULL,
                    statut TEXT NOT NULL,
                    payload_json TEXT NOT NULL,
                    synced_at TEXT NOT NULL
                )
                """
            )
            connection.execute(
                """
                CREATE INDEX IF NOT EXISTS idx_cached_res_station
                ON cached_reservations (station_id, date_debut, date_fin)
                """
            )
            connection.execute(
                """
                CREATE INDEX IF NOT EXISTS idx_cached_res_auth
                ON cached_reservations (auth_mode, auth_hash)
                """
            )
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS offline_events (
                    id TEXT PRIMARY KEY,
                    event_type TEXT NOT NULL,
                    reservation_id TEXT,
                    session_id TEXT,
                    payload_json TEXT NOT NULL,
                    created_at TEXT NOT NULL,
                    synced_at TEXT
                )
                """
            )
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS offline_metadata (
                    key TEXT PRIMARY KEY,
                    value TEXT NOT NULL
                )
                """
            )

    def configure_grace_periods(self, start_minutes: int | None = None, end_minutes: int | None = None):
        """Update local validation tolerances from the backend cache payload."""
        global START_GRACE_MINUTES, END_GRACE_MINUTES
        if isinstance(start_minutes, int) and start_minutes >= 0:
            START_GRACE_MINUTES = start_minutes
        if isinstance(end_minutes, int) and end_minutes >= 0:
            END_GRACE_MINUTES = end_minutes

    def replace_reservations(self, reservations: list[dict[str, Any]], station_id: str = "") -> int:
        """Replace cached reservations for one station or for the whole kiosk cache."""
        synced_at = utc_now().isoformat()
        with self._connect() as connection:
            if station_id:
                connection.execute("DELETE FROM cached_reservations WHERE station_id = ?", (station_id,))
            else:
                connection.execute("DELETE FROM cached_reservations")

            for item in reservations:
                connection.execute(
                    """
                    INSERT OR REPLACE INTO cached_reservations (
                        id_reservation,
                        reference_code,
                        station_id,
                        station_nom,
                        emplacement_id,
                        emplacement_numero,
                        auth_mode,
                        auth_hash,
                        auth_expires_at,
                        date_debut,
                        date_fin,
                        statut,
                        payload_json,
                        synced_at
                    ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                    """,
                    (
                        item["id_reservation"],
                        item["reference_code"],
                        item["station_id"],
                        item["station_nom"],
                        item["emplacement_id"],
                        int(item["emplacement_numero"]),
                        item["auth_mode"],
                        item["auth_hash"],
                        item.get("auth_expires_at"),
                        item["date_debut"],
                        item["date_fin"],
                        item["statut"],
                        json.dumps(item),
                        synced_at,
                    ),
                )
            connection.execute(
                """
                INSERT OR REPLACE INTO offline_metadata (key, value)
                VALUES ('last_sync', ?)
                """,
                (synced_at,),
            )
        return len(reservations)

    def stats(self) -> dict[str, Any]:
        """Return a compact degraded-mode cache status."""
        with self._connect() as connection:
            reservation_count = connection.execute("SELECT COUNT(*) FROM cached_reservations").fetchone()[0]
            event_count = connection.execute(
                "SELECT COUNT(*) FROM offline_events WHERE synced_at IS NULL"
            ).fetchone()[0]
            metadata_sync = connection.execute(
                "SELECT value FROM offline_metadata WHERE key = 'last_sync'"
            ).fetchone()
            last_sync = metadata_sync["value"] if metadata_sync else None
        return {
            "db_path": str(self.db_path),
            "cached_reservations": reservation_count,
            "pending_events": event_count,
            "last_sync": last_sync,
        }

    def pending_events(self, limit: int = 50) -> list[dict[str, Any]]:
        """Return unsynced local events ready to be reconciled by the backend."""
        with self._connect() as connection:
            rows = connection.execute(
                """
                SELECT id, event_type, reservation_id, session_id, payload_json, created_at
                FROM offline_events
                WHERE synced_at IS NULL
                ORDER BY created_at, id
                LIMIT ?
                """,
                (limit,),
            ).fetchall()

        return [
            {
                "id": row["id"],
                "event_type": row["event_type"],
                "reservation_id": row["reservation_id"],
                "session_id": row["session_id"],
                "payload": json.loads(row["payload_json"]),
                "created_at": row["created_at"],
            }
            for row in rows
        ]

    def mark_events_synced(self, event_ids: list[str]) -> int:
        """Mark backend-accepted events so they are not replayed."""
        ids = [str(event_id) for event_id in event_ids if event_id]
        if not ids:
            return 0

        synced_at = utc_now().isoformat()
        placeholders = ", ".join("?" for _ in ids)
        with self._connect() as connection:
            cursor = connection.execute(
                f"""
                UPDATE offline_events
                SET synced_at = ?
                WHERE synced_at IS NULL
                AND id IN ({placeholders})
                """,
                [synced_at, *ids],
            )
            return cursor.rowcount

    def _row_payload(self, row: sqlite3.Row) -> dict[str, Any]:
        return json.loads(row["payload_json"])

    def _row_matches_borne(self, row: sqlite3.Row, borne_id: str = "") -> bool:
        """Return whether a cached row belongs to the requested physical cabinet."""
        if not borne_id:
            return True
        return str(self._row_payload(row).get("borne_id") or "") == str(borne_id)

    def _active_rows(self, now: datetime, station_id: str = "") -> list[sqlite3.Row]:
        with self._connect() as connection:
            query = """
                SELECT * FROM cached_reservations
                WHERE statut IN ('confirmee', 'active')
                AND datetime(date_fin) >= datetime(?)
                AND datetime(date_debut) <= datetime(?)
            """
            params: list[Any] = [
                (now - timedelta(minutes=END_GRACE_MINUTES)).isoformat(),
                (now + timedelta(minutes=START_GRACE_MINUTES)).isoformat(),
            ]
            if station_id:
                query += " AND station_id = ?"
                params.append(station_id)
            query += " ORDER BY date_debut, id_reservation"
            return list(connection.execute(query, params))

    def _validate_time_window(self, row: sqlite3.Row, now: datetime):
        start = parse_datetime(row["date_debut"])
        end = parse_datetime(row["date_fin"])
        auth_expiration = parse_datetime(row["auth_expires_at"])

        if start and start - timedelta(minutes=START_GRACE_MINUTES) > now:
            raise ValueError("La reservation n'a pas encore commence.")
        if end and end + timedelta(minutes=END_GRACE_MINUTES) < now:
            raise ValueError("La fenetre de reservation est expiree.")
        if auth_expiration and auth_expiration + timedelta(minutes=END_GRACE_MINUTES) < now:
            raise ValueError("Le moyen d'authentification est expire.")

    def _ensure_no_paid_window_conflict(self, row: sqlite3.Row, now: datetime):
        """Avoid early-starting a bay still owned by the previous paid slot."""
        start = parse_datetime(row["date_debut"])
        if not start or now >= start:
            return

        with self._connect() as connection:
            conflict = connection.execute(
                """
                SELECT id_reservation
                FROM cached_reservations
                WHERE emplacement_id = ?
                AND id_reservation != ?
                AND statut IN ('confirmee', 'active')
                AND datetime(date_debut) <= datetime(?)
                AND datetime(date_fin) > datetime(?)
                LIMIT 1
                """,
                (
                    row["emplacement_id"],
                    row["id_reservation"],
                    now.isoformat(),
                    now.isoformat(),
                ),
            ).fetchone()

        if conflict:
            raise ValueError("L'emplacement est encore reserve par le creneau precedent.")

    def _success(self, row: sqlite3.Row, auth_mode: str, auth_source: str) -> OfflineAuthResult:
        reservation = self._row_payload(row)
        session_id = f"offline-{uuid.uuid4()}"
        self.record_event(
            "offline_session_started",
            reservation_id=reservation["id_reservation"],
            session_id=session_id,
            payload={
                "auth_mode": auth_mode,
                "auth_source": auth_source,
                "reservation": reservation,
            },
        )
        return OfflineAuthResult(reservation=reservation, session_id=session_id)

    def authenticate(self, payload: dict[str, Any], station_id: str = "", borne_id: str = "") -> OfflineAuthResult:
        """Validate a terminal authentication payload against the local cache."""
        auth_mode = str(payload.get("auth_mode") or "").strip().lower()
        auth_value = str(payload.get("auth_value") or "").strip()
        reservation_code = str(payload.get("reservation_code") or "").strip().upper()
        now = utc_now()

        parsed_qr = parse_qr_payload(auth_value)
        if parsed_qr:
            auth_mode = auth_mode or "qr"
            auth_value = parsed_qr["token"]
            reservation_code = reservation_code or parsed_qr["reservation_code"]

        if not auth_mode or not auth_value:
            raise ValueError("auth_mode et auth_value sont obligatoires.")

        if auth_mode == "rfid" and not reservation_code:
            auth_hash = hash_secret(auth_value)
            matches = [
                row
                for row in self._active_rows(now, station_id=station_id)
                if row["auth_mode"] == "rfid"
                and row["auth_hash"] == auth_hash
                and self._row_matches_borne(row, borne_id=borne_id)
            ]
            if not matches:
                raise ValueError("Aucune reservation offline active pour ce badge RFID.")
            if len(matches) > 1:
                raise ValueError("Plusieurs reservations offline correspondent a ce badge RFID.")
            self._validate_time_window(matches[0], now)
            self._ensure_no_paid_window_conflict(matches[0], now)
            return self._success(matches[0], auth_mode="rfid", auth_source="rfid")

        if not reservation_code:
            raise ValueError("reservation_code est obligatoire en mode QR ou code SMS.")

        with self._connect() as connection:
            row = connection.execute(
                """
                SELECT * FROM cached_reservations
                WHERE reference_code = ?
                """,
                (reservation_code,),
            ).fetchone()

        if row is None:
            raise ValueError("Reservation absente du cache offline.")
        if station_id and row["station_id"] != station_id:
            raise ValueError(f"Reservation associee a une autre station: {row['station_nom']}.")
        if not self._row_matches_borne(row, borne_id=borne_id):
            reservation = self._row_payload(row)
            raise ValueError(f"Reservation associee a une autre borne: {reservation.get('borne_nom') or '-'}.")
        if row["auth_mode"] != auth_mode:
            raise ValueError("Mauvais moyen d'authentification.")

        self._validate_time_window(row, now)
        self._ensure_no_paid_window_conflict(row, now)
        if row["auth_hash"] != hash_secret(auth_value):
            raise ValueError("Authentification offline refusee.")
        return self._success(row, auth_mode=auth_mode, auth_source="typed_or_scanned")

    def record_event(self, event_type: str, reservation_id: str, session_id: str, payload: dict[str, Any]):
        """Append a local event that the backend can reconcile later."""
        with self._connect() as connection:
            connection.execute(
                """
                INSERT INTO offline_events (
                    id, event_type, reservation_id, session_id, payload_json, created_at, synced_at
                ) VALUES (?, ?, ?, ?, ?, ?, NULL)
                """,
                (
                    str(uuid.uuid4()),
                    event_type,
                    reservation_id,
                    session_id,
                    json.dumps(payload),
                    utc_now().isoformat(),
                ),
            )
